func TestForms(t *testing.T) {
	for _, form := range forms {
		got, err := statementsOf(t, "    "+form.statement)
		if err != nil {
			t.Errorf("%s: %v", form.statement, err)
		} else if got != form.want {
			t.Errorf("%s:\ngot\n%s\nwant\n%s", form.statement, got, form.want)
		}
	}
}
